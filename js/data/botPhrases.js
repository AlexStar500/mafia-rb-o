const AGGRESSIVE_INTENTS = new Set(["accuse", "result-mafia", "vote-call"]);

export function isAggressiveIntent(intent) {
  return AGGRESSIVE_INTENTS.has(intent);
}

export function pickBotLine(intent, style, vars = {}, rng = Math.random) {
  const group = BOT_LINES[intent] ?? BOT_LINES.emote;
  const styled = group[style] ?? [];
  const pool = [...(group.common ?? []), ...styled];
  if (!pool.length) return "";
  let line = pool[Math.floor(rng() * pool.length) % pool.length];
  const values = {
    name: vars.name ?? "кто-то",
    me: vars.me ?? "я",
    day: vars.day ?? "",
  };
  line = line.replace(/\{name\}/g, values.name).replace(/\{me\}/g, values.me).replace(/\{day\}/g, String(values.day));
  return line.replace(/\s+/g, " ").trim().slice(0, 160);
}

